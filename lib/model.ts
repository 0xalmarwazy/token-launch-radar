// The token radar's model: one snapshot of the protocol universe in, one ranked
// board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and every other protocol that passes the launch-candidate rule below:
// the early rows the radar exists to find. A protocol is a launch candidate when
// its record shows no token and it is not a wrapped, staked or bridged product,
// not an exchange, and not a versioned pool of another protocol. Protocols whose
// token already trades are kept apart in the dashboard's Live view and never
// ranked: their market cap is the market's own value, not a model's.
//
// Implied value follows only from the snapshot's own figures:
//
//   base        = tvl_usd x BASE_MULTIPLE
//   growth      = clamp(change_7d, -50, +100) per cent (null counts as 0)
//   growthMult  = 1 + 0.40 x (growth / 100)              in [0.80, 1.40]
//   tenure      = 0.70 + 0.30 x min(age_days, 1095) / 1095, age unknown: 365 days
//   breadth     = 1 + 0.02 x min(chains - 1, 5)          in [1.00, 1.10]
//   implied     = max(1, round(base x growthMult x tenure x breadth))
//
// TVL is the size of the business a token would price; the seven-day change is
// its momentum, clamped so one wild week cannot decide the board; tenure is how
// long the protocol has run with no token, capped at three years; breadth is how
// many chains it runs on, capped at six. No protocol name is ever special-cased:
// the same function scores every row, and the dashboard states the formula.

import { farmPlan } from './farm.ts';

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  tenure_floor: number;
  tenure_range: number;
  tenure_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.4,
  growth_floor: -50,
  growth_cap: 100,
  tenure_floor: 0.7,
  tenure_range: 0.3,
  tenure_days: 1095,
  unknown_age_days: 365,
  breadth_per_chain: 0.02,
  breadth_max_chains: 5,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the dashboard's Live view carries, by market cap. */
export const LIVE_ROWS = 24;

